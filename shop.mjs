//    형식을 지어내지 않는다. 승인 뒤 파트너스에서 링크 하나 만들어 보고 그 형식을 넣는다.
//
// 🔴 규정 A6·E1 — 검색어에 제품명·브랜드·가격을 쓰지 않는다. 우리가 쓴 "기준" 의 말만 쓴다.

export const APPROVED = process.env.COUPANG_APPROVED === "1";
export const TEMPLATE = process.env.COUPANG_LINK_TEMPLATE || "";
export const ready = () => APPROVED && TEMPLATE.includes("{q}");
export const link = q => ready() ? TEMPLATE.replace("{q}", encodeURIComponent(q)) : null;

