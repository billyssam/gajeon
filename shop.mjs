// 다리 한 블록. 켜지지 않았으면 빈 문자열 — 자리만 비어 있고 거짓말은 없다.
export function bridge(seed, esc) {
  if (!ready()) return "";
  const qs = SHOP[seed] || [];
  if (!qs.length) return "";
  return `\n<div class="shop"><b>이 기준으로 좁혀 보기</b>\n`
    + qs.map(q => `<a href="${esc(link(q))}" target="_blank" rel="nofollow sponsored noopener">${esc(q)}</a>`).join("\n")
    + `\n<p>쿠팡 검색 결과로 연결됩니다. 어떤 제품을 권하는 링크가 아닙니다.</p></div>`;
}
